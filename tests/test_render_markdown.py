"""Tests for render_markdown — pure string formatter that consumes already-
fetched summaries and returns a markdown string.

render_markdown calls wallclock_work_seconds() / engaged_with_ai_seconds() only
when `umbrella_today` is truthy, and those would hit the network. We monkey-
patch them so the formatter is exercised in isolation.
"""
import os
import time
from datetime import datetime, timezone

import pytest

import aggregate
from aggregate import render_markdown


DAY = datetime(2026, 1, 15, 0, 0, 0, tzinfo=timezone.utc)


@pytest.fixture
def m_wallclock(monkeypatch):
    """Stub out the two helpers render_markdown calls inside umbrella_today."""
    monkeypatch.setattr(aggregate, "wallclock_work_seconds", lambda day: 5400.0)
    monkeypatch.setattr(aggregate, "engaged_with_ai_seconds", lambda day: 1800.0)


# ── minimal / empty inputs ──────────────────────────────────────────────────

