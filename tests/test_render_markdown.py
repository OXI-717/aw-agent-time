# ── umbrella_today (coding/other) ───────────────────────────────────────────

def test_render_no_keyboard_time_shows_placeholder(monkeypatch):
    # Genuinely no keyboard activity at all → "работы нет".
    monkeypatch.setattr(aggregate, "wallclock_work_seconds", lambda day: 0.0)
    monkeypatch.setattr(aggregate, "engaged_with_ai_seconds", lambda day: 0.0)
