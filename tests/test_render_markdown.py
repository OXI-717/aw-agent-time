def test_render_no_warning_for_closed_day():
    md = render_markdown(DAY, states={}, engagement={}, autonomous={}, now=AFTER_CLOSE)
    assert "День не закрыт — данные частичные" not in md
    assert "⏳ |" not in md  # no day-row carries the open marker


def test_render_marks_open_day_in_daily_table():
    rows = [
        (datetime(2026, 1, 14, tzinfo=timezone.utc), {"Client B": 1800}, 1800.0, 0.0),
        (DAY, {"Client A": 3600}, 3600.0, 0.0),
    ]
    md = render_markdown(
        DAY, states={}, engagement={}, autonomous={}, daily_rows=rows, now=MIDDAY
    )
    assert "| Чт 15 янв ⏳ |" in md
    assert "| Ср 14 янв |" in md  # yesterday's window has closed → no marker
    assert "_⏳ — день не закрыт" in md


def test_render_daily_table_unmarked_when_all_days_closed():
    rows = [(DAY, {"Client A": 3600}, 3600.0, 0.0)]
